//! Differentiation against numbers from Origin 2016 (`differentiate`).
//!
//! Reference script: `tools/origin-ref/diff-suite1.labtalk.txt` (run with `run-labtalk-data.ps1`).
//! Inputs are the closed-form columns of the script. Tolerance: relative 1e-10 (the smoothing
//! derivatives solve a small least-squares system, the plain ones agree to rounding).

use sheaf_calc::{DiffOptions, differentiate};
#[allow(dead_code)]
fn grid(n: usize, start: f64, step: f64) -> Vec<f64> {
    (0..n).map(|i| start + i as f64 * step).collect()
}

#[allow(dead_code)]
fn close(name: &str, got: f64, want: f64, tol: f64) {
    if want.is_nan() {
        assert!(got.is_nan(), "{name}: got {got:?}, Origin gave NaN");
        return;
    }
    let ok = (got - want).abs() <= tol * want.abs().max(1.0);
    assert!(ok, "{name}: got {got:?}, Origin gave {want:?}");
}

#[allow(dead_code)]
fn check(name: &str, got: &[f64], samples: &[(usize, f64)], tol: f64) {
    for &(i, w) in samples {
        close(&format!("{name}[{i}]"), got[i], w, tol);
    }
}

fn inputs() -> (Vec<f64>, Vec<f64>) {
    let a = grid(101, 0.0, 0.1);
    let b = a.iter().map(|x| x.sin() + 0.1 * x * x).collect();
    (a, b)
}

