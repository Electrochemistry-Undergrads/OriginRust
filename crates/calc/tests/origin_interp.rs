#[test]
fn unsorted_data_is_sorted_and_missing_pairs_dropped() {
    let (x, y) = data();
    let at = [0.5, 3.3, 9.9];
    let want = interp1(&x, &y, &at, &InterpOptions::default());
    let mut xs = x.clone();
    let mut ys = y.clone();
    xs.reverse();
    ys.reverse();
    xs.push(4.0);
    ys.push(f64::NAN);
    let got = interp1(&xs, &ys, &at, &InterpOptions::default());
    check("shuffled", &got, &[(0, want[0]), (1, want[1]), (2, want[2])], 1e-14);
}
