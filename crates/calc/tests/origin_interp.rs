//! Interpolation against numbers from Origin (`interp1`, `interp1xy`).
//!
//! Reference script: `tools/origin-ref/interp-suite1.labtalk.txt` (run with `run-labtalk-data.ps1`).
//! Data: x = 10 ((i-1)/10)^1.3 for i = 1..11 (uneven), y = sin(x) + 0.1 x; targets
//! -1..11 step 0.37 (33 points, inside and outside the data). Tolerance: relative 1e-10.
//! The cubic B-spline method is in `origin_bspline.rs`.

use sheaf_calc::{Extrapolation, InterpMethod, InterpOptions, SplineBoundary, interp1, interp1xy};
#[allow(dead_code)]
fn grid(n: usize, start: f64, step: f64) -> Vec<f64> {
    (0..n).map(|i| start + i as f64 * step).collect()
}

#[allow(dead_code)]
fn close(name: &str, got: f64, want: f64, tol: f64) {
    if want.is_nan() {
        assert!(got.is_nan(), "{name}: got {got:?}, Origin gave NaN");
        return;
    }
    let ok = (got - want).abs() <= tol * want.abs().max(1.0);
    assert!(ok, "{name}: got {got:?}, Origin gave {want:?}");
}

#[allow(dead_code)]
fn check(name: &str, got: &[f64], samples: &[(usize, f64)], tol: f64) {
    for &(i, w) in samples {
        close(&format!("{name}[{i}]"), got[i], w, tol);
    }
}

fn data() -> (Vec<f64>, Vec<f64>) {
    let x: Vec<f64> = (0..11).map(|i| 10.0 * (i as f64 / 10.0).powf(1.3)).collect();
    let y = x.iter().map(|x| x.sin() + 0.1 * x).collect();
    (x, y)
}

