//! Normalisation against numbers from Origin (`normalize`).
//!
//! Reference script: `tools/origin-ref/normalize-suite1.labtalk.txt` (run with `run-labtalk-data.ps1`).
//! Inputs: x = 0..10 step 0.1; B = sin(x) + 0.3 cos(7x) + 0.05 x^2 + 0.2; C = round(2 sin(x))
//! (repeated values for the mode); D = B with a missing value in row 20. Tolerance: relative 1e-12.

use sheaf_calc::{NormalizeMethod, normalize};
#[allow(dead_code)]
fn grid(n: usize, start: f64, step: f64) -> Vec<f64> {
    (0..n).map(|i| start + i as f64 * step).collect()
}

#[allow(dead_code)]
fn close(name: &str, got: f64, want: f64, tol: f64) {
    if want.is_nan() {
        assert!(got.is_nan(), "{name}: got {got:?}, Origin gave NaN");
        return;
    }
    let ok = (got - want).abs() <= tol * want.abs().max(1.0);
    assert!(ok, "{name}: got {got:?}, Origin gave {want:?}");
}

#[allow(dead_code)]
fn check(name: &str, got: &[f64], samples: &[(usize, f64)], tol: f64) {
    for &(i, w) in samples {
        close(&format!("{name}[{i}]"), got[i], w, tol);
    }
}

fn x() -> Vec<f64> {
    grid(101, 0.0, 0.1)
}

