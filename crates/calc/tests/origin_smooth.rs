//! Smoothing against numbers from Origin 2016 (`smooth`).
//!
//! Reference script: `tools/origin-ref/smooth-suite1.labtalk.txt` (run with `run-labtalk-data.ps1`).
//! Input: x = 0..10 step 0.1 (101 points), y = sin(x) + 0.3 cos(7x) + 0.05 x^2 (the row-20 copy has
//! a missing value). Tolerance: relative 1e-10. The FFT filter is not implemented.

use sheaf_calc::{Boundary, SmoothMethod, SmoothOptions, smooth};
#[allow(dead_code)]
fn grid(n: usize, start: f64, step: f64) -> Vec<f64> {
    (0..n).map(|i| start + i as f64 * step).collect()
}

#[allow(dead_code)]
fn close(name: &str, got: f64, want: f64, tol: f64) {
    if want.is_nan() {
        assert!(got.is_nan(), "{name}: got {got:?}, Origin gave NaN");
        return;
    }
    let ok = (got - want).abs() <= tol * want.abs().max(1.0);
    assert!(ok, "{name}: got {got:?}, Origin gave {want:?}");
}

#[allow(dead_code)]
fn check(name: &str, got: &[f64], samples: &[(usize, f64)], tol: f64) {
    for &(i, w) in samples {
        close(&format!("{name}[{i}]"), got[i], w, tol);
    }
}

fn input() -> Vec<f64> {
    grid(101, 0.0, 0.1).iter().map(|x| x.sin() + 0.3 * (7.0 * x).cos() + 0.05 * x * x).collect()
}

