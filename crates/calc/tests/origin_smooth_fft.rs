//! `tools/origin-ref/smooth-fft-*.labtalk.txt` (run with `run-labtalk-data.ps1`) and are copied
//! below at full precision. Tolerance: 1e-12 absolute (the values are of order 1; the largest
//! difference seen when the rule was found was 4e-15, from rounding in the two FFT
//! implementations).
//!
//! The cases include the ones where the cutoff falls exactly on a frequency bin, which only agree
//! with Origin because the comparison is done with the same floating-point expressions.

use sheaf_calc::{SmoothMethod, SmoothOptions, smooth, smooth_xy};

const TOL: f64 = 1e-12;

fn fft(npts: usize) -> SmoothOptions {
    SmoothOptions { method: SmoothMethod::FftFilter, npts, ..SmoothOptions::default() }
}

fn same(name: &str, got: &[f64], want: &[f64]) {
    assert_eq!(got.len(), want.len(), "{name}: length");
    for (i, (g, w)) in got.iter().zip(want).enumerate() {
        if w.is_nan() {
            assert!(g.is_nan(), "{name}[{i}]: got {g:?}, Origin gave NaN");
        } else {
            assert!((g - w).abs() <= TOL * w.abs().max(1.0), "{name}[{i}]: got {g:?}, Origin gave {w:?}");
        }
    }
}

