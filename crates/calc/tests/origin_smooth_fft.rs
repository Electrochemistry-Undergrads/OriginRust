#[test]
fn uniform_grids_match_origin() {
    for &(n, npts, y, want) in GRID {
        let x: Vec<f64> = (0..n).map(|i| 0.1 * i as f64).collect();
        same(&format!("n={n} npts={npts}"), &smooth_xy(&x, y, &fft(npts)), want);
    }
}

#[test]
fn irregular_descending_missing_and_tiny_inputs_match_origin() {
    for &(name, npts, x, y, want) in EXPLICIT {
        same(&format!("{name} npts={npts}"), &smooth_xy(x, y, &fft(npts)), want);
    }
}

#[test]
fn long_series_use_one_percent_of_the_points_for_the_baseline() {
    for &(n, dx, npts, samples) in BIG {
        let x: Vec<f64> = (0..n).map(|i| i as f64 * dx).collect();
        let y: Vec<f64> = x.iter().map(|v| (12345.678 * v).sin() + 2.0 * v + 0.5).collect();
        let got = smooth_xy(&x, &y, &fft(npts));
        for &(i, want) in samples {
            assert!(
                (got[i] - want).abs() <= 1e-11 * want.abs().max(1.0),
                "n={n} npts={npts} [{i}]: got {:?}, Origin gave {want:?}",
                got[i]
            );
        }
    }
}

#[test]
fn without_x_the_row_number_is_the_x_value() {
    // Row numbers have spacing 1, so `smooth` equals `smooth_xy` with x = 0, 1, 2, ...
    let y: Vec<f64> = (0..40).map(|i| ((i * 7 % 13) as f64) * 0.1).collect();
    let x: Vec<f64> = (0..40).map(f64::from).collect();
    same("row x", &smooth(&y, &fft(3)), &smooth_xy(&x, &y, &fft(3)));
}

#[test]
fn constant_data_is_not_changed() {
    let x: Vec<f64> = (0..30).map(|i| 0.5 * i as f64).collect();
    let flat = vec![4.25; 30];
    {
        let y = &flat;
        for npts in [1, 4, 10] {
            for (g, w) in smooth_xy(&x, y, &fft(npts)).iter().zip(y) {
                assert!((g - w).abs() < 1e-12, "{g} vs {w}");
            }
        }
    }
}
