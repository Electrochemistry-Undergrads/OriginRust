//! Lowess, Loess and binomial smoothing against numbers from Origin (`smooth method:=lw|le|bm`).
//!
//! Reference scripts: `tools/origin-ref/smooth-local-suite1.labtalk.txt` (x = 0..10 step 0.1, 101 points,
//! y = sin(x) + 0.3 cos(7x) + 0.05 x^2) and `smooth-local-suite2.labtalk.txt` (x = i^1.3 / 10, i = 1..100,
//! y = sin(x) + 0.3 cos(3x) + 0.02 x^2; row 20 missing in the copy used for the last columns), run with
//! `run-labtalk-data.ps1`. Tolerance: relative 1e-10. What the runs showed is in `docs/spec/analysis-tools.md`, section 3.

use sheaf_calc::{Boundary, LocalSpan, SmoothMethod, SmoothOptions, smooth_xy};

fn close(name: &str, got: f64, want: f64) {
    let ok = (got - want).abs() <= 1e-10 * want.abs().max(1.0);
    assert!(ok, "{name}: got {got:?}, Origin gave {want:?}");
}

fn check(name: &str, got: &[f64], samples: &[(usize, f64)]) {
    for &(i, w) in samples {
        close(&format!("{name}[{i}]"), got[i], w);
    }
}

fn suite1() -> (Vec<f64>, Vec<f64>) {
    let x: Vec<f64> = (0..101).map(|i| i as f64 * 0.1).collect();
    let y = x.iter().map(|x| x.sin() + 0.3 * (7.0 * x).cos() + 0.05 * x * x).collect();
    (x, y)
}

fn suite2() -> (Vec<f64>, Vec<f64>) {
    let x: Vec<f64> = (1..=100).map(|i| (i as f64).powf(1.3) / 10.0).collect();
    let y = x.iter().map(|x| x.sin() + 0.3 * (3.0 * x).cos() + 0.02 * x * x).collect();
    (x, y)
}

fn opts(method: SmoothMethod, npts: usize, boundary: Boundary) -> SmoothOptions {
    SmoothOptions { method, npts, boundary }
}
