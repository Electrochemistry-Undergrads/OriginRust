#[test]
fn a_missing_value_is_left_out_and_comes_back_as_nan() {
    let (x, mut y) = suite2();
    y[19] = f64::NAN;
    let lw = smooth_xy(&x, &y, &opts(SmoothMethod::Lowess { span: LocalSpan::Proportion(0.2) }, 5, Boundary::None));
    assert!(lw[19].is_nan());
    check(
        "lw_missing",
        &lw,
        &[
            (0, 0.7083580852080922),
            (1, 0.7048621324385412),
            (2, 0.6986587297637801),
            (18, 0.06312860994064555),
            (20, 0.282034083180837),
            (50, 5.388933054284177),
            (98, 31.21752220282667),
            (99, 32.06899410856008),
        ],
    );
    let bm = smooth_xy(&x, &y, &opts(SmoothMethod::Binomial { order: 2 }, 5, Boundary::None));
    assert!(bm[19].is_nan());
    check(
        "bm_missing",
        &bm,
        &[
            (0, 0.38663436338450985),
            (1, 0.4480266521030169),
            (2, 0.487182516609045),
            (18, -0.4185808927606137),
            (20, -0.39090809523295456),
            (50, 4.913721493636562),
            (98, 31.81597106796509),
            (99, 32.8547566080721),
        ],
    );
}

#[test]
fn polynomial_order_weighting_and_boundary_do_not_change_lowess() {
    let (x, y) = suite1();
    let base = smooth_xy(&x, &y, &opts(SmoothMethod::Lowess { span: LocalSpan::Proportion(0.2) }, 5, Boundary::None));
    let other =
        smooth_xy(&x, &y, &opts(SmoothMethod::Lowess { span: LocalSpan::Proportion(0.2) }, 11, Boundary::Reflect));
    assert_eq!(base, other);
}
