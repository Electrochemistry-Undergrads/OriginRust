"""Reference numbers for acceptance sampling (T369), from scipy.

Usage: python tools/acceptance-ref.py > crates/calc/tests/fixtures/acceptance_reference.rs

For each case: the single sampling plan with the smallest n found by brute force (every c from 0, every n
from c + 1), the binomial probabilities of acceptance at a few fractions, and with a lot size the AOQ, ATI
and the AOQL (scipy.optimize.minimize_scalar, bounded, then refined).
"""
from scipy.stats import binom
from scipy.optimize import minimize_scalar

DESIGNS = [
    # aql, ltpd, alpha, beta
    (0.01, 0.05, 0.05, 0.10),
    (0.005, 0.03, 0.05, 0.10),
    (0.02, 0.08, 0.05, 0.10),
    (0.01, 0.10, 0.05, 0.05),
    (0.001, 0.01, 0.01, 0.10),
]
PLANS = [(50, 1, 1000), (89, 2, 2000), (125, 3, 500), (20, 0, 200)]
FRACTIONS = [0.0, 0.005, 0.01, 0.02, 0.05, 0.1, 0.2]


def design(aql, ltpd, alpha, beta):
    c = 0
    while True:
        n = c + 1
        while binom.cdf(c, n, ltpd) > beta:
            n += 1
        if binom.cdf(c, n, aql) >= 1 - alpha:
            return n, c
        c += 1


def aoq(n, c, lot, p):
    return p * binom.cdf(c, n, p) * (lot - n) / lot


def aoql(n, c, lot):
    grid = [i / 2000 for i in range(2001)]
    best = max(grid, key=lambda p: aoq(n, c, lot, p))
    r = minimize_scalar(lambda p: -aoq(n, c, lot, p), bounds=(max(0, best - 1e-3), min(1, best + 1e-3)),
                        method="bounded", options={"xatol": 1e-13})
    return -r.fun, r.x


print("// Generated by tools/acceptance-ref.py (scipy). Do not edit.")
print("/// (aql, ltpd, alpha, beta, n, c)")
print("pub const DESIGNS: &[(f64, f64, f64, f64, u64, u64)] = &[")
for aql, ltpd, alpha, beta in DESIGNS:
    n, c = design(aql, ltpd, alpha, beta)
    print(f"    ({aql!r}, {ltpd!r}, {alpha!r}, {beta!r}, {n}, {c}),")
print("];")
print("/// (n, c, lot, p, Pa, AOQ, ATI)")
print("pub const CURVES: &[(u64, u64, u64, f64, f64, f64, f64)] = &[")
for n, c, lot in PLANS:
    for p in FRACTIONS:
        pa = binom.cdf(c, n, p)
        print(f"    ({n}, {c}, {lot}, {p!r}, {float(pa)!r}, {float(aoq(n, c, lot, p))!r}, {float(n + (1 - pa) * (lot - n))!r}),")
print("];")
print("/// (n, c, lot, AOQL, p at the AOQL)")
print("pub const AOQL: &[(u64, u64, u64, f64, f64)] = &[")
for n, c, lot in PLANS:
    q, p = aoql(n, c, lot)
    print(f"    ({n}, {c}, {lot}, {float(q)!r}, {float(p)!r}),")
print("];")
