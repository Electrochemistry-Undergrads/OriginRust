"""Turns the raw outputs of the Origin reference runs (stats2-anova2 and stats2-np) into the Rust fixture file
crates/calc/tests/fixtures/stats2_origin.rs.

usage: python -I stats2-make-fixture.py ANOVA2_CASES.json ANOVA2.out NP_CASES.json NP.out [NP2_CASES.json NP2.out] OUT.rs
"""
import json, re, sys, math

def dumps(path):
    lines = open(path, encoding='utf-8', errors='replace').read().split('\n')
    out = []; i = 0
    while i < len(lines):
        m = re.match(r'#SHEET (\S+) (\d+) (\d+)', lines[i])
        if m:
            n = int(m.group(2)); rows = [l.split('\t') for l in lines[i + 1:i + 1 + n]]
            out.append(rows); i += n + 1
        else:
            i += 1
    return out

def cell(rows, r, c):
    try:
        x = rows[r][c]
    except IndexError:
        return None
    return float(x) if x != '' else None

def f(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return 'f64::NAN'
    return repr(float(v)) if not float(v).is_integer() else repr(float(v))

def arr(vals):
    return '[' + ', '.join(f(v) for v in vals) + ']'

def sl(vals):
    return '&[' + ', '.join(f(v) for v in vals) + ']'

args = sys.argv[1:]
a2_cases, a2_out, np_cases, np_out = args[:4]
extra = args[4:-1]
out_path = args[-1]
o = []
o.append('//! Numbers copied from Origin reference runs (generated by tools/origin-ref/stats2-make-fixture.py;')
o.append('//! the scripts and the raw output are in tools/origin-ref/stats2-*). Do not edit by hand.')
o.append('#![allow(clippy::excessive_precision, dead_code)]')
o.append('')
o.append('pub struct Comp { pub diff: f64, pub sem: f64, pub stat: f64, pub prob: f64, pub sig: bool, pub lcl: f64, pub ucl: f64 }')
o.append('pub struct TwoWay {')
o.append('    pub name: &\'static str, pub a: &\'static [usize], pub b: &\'static [usize], pub y: &\'static [f64],')
o.append('    pub interaction: bool, pub method: u8,')
o.append('    /// Rows A, B, interaction, model, error, total: DF, SS, MS, F, P (NaN where Origin shows nothing).')
o.append('    pub table: [[f64; 5]; 6],')
o.append('    /// N, mean, SD, SEM of each level of A, of B, of each cell (A changes slowest) and of all the data.')
o.append('    pub desc_a: &\'static [[f64; 4]], pub desc_b: &\'static [[f64; 4]], pub desc_cells: &\'static [[f64; 4]], pub desc_all: [f64; 4],')
o.append('    pub comp_a: &\'static [Comp], pub comp_b: &\'static [Comp], pub comp_cells: &\'static [Comp],')
o.append('}')
o.append('')
# ---------- two-way
cases = json.load(open(a2_cases)); ds = dumps(a2_out)
k = 0
o.append('pub const TWO_WAY: &[TwoWay] = &[')
for c in cases:
    for (inter, method) in c['runs']:
        rows = ds[k]; k += 1
        if method > 5:
            continue  # the Holm methods are not built
        if c['name'] == 'empty' and inter:
            continue  # Origin's table is not meaningful for an empty cell; the test checks that we refuse
        col = lambda j: [cell(rows, r, j) for r in range(len(rows))]
        t = col(3)
        if t[0] != 0:
            continue
        table = [[t[1 + 5 * r + q] for q in range(5)] for r in range(6)]
        nA, nB = c['nA'], c['nB']
        def desc(j, n):
            v = col(j)
            return [[v[4 * i + q] for q in range(4)] for i in range(n)]
        def comps(base, nlev):
            if method == 0 or cell(rows, 0, base) is None:
                return []
            npair = nlev * (nlev - 1) // 2
            cols = {nm: col(base + 1 + off) for off, nm in enumerate(['idx', 'diff', 'sem', 'dof', 'stat', 'prob', 'sig', 'lcl', 'ucl'])}
            return [(cols['diff'][i], cols['sem'][i], cols['stat'][i], cols['prob'][i], cols['sig'][i], cols['lcl'][i], cols['ucl'][i]) for i in range(npair)]
        def comp_src(lst):
            return '&[' + ', '.join(f'Comp {{ diff: {f(d)}, sem: {f(s)}, stat: {f(st)}, prob: {f(p)}, sig: {"true" if sg else "false"}, lcl: {f(l)}, ucl: {f(u)} }}' for d, s, st, p, sg, l, u in lst) + ']'
        a = [r[0] - 1 for r in c['rows']]; b = [r[1] - 1 for r in c['rows']]; y = [r[2] for r in c['rows']]
        o.append('    TwoWay {')
        o.append(f'        name: "{c["name"]}", a: &{a}, b: &{b}, y: {sl(y)}, interaction: {"true" if inter else "false"}, method: {method},')
        o.append('        table: [' + ', '.join(arr(r) for r in table) + '],')
        o.append(f'        desc_a: &[{", ".join(arr(r) for r in desc(4, nA))}], desc_b: &[{", ".join(arr(r) for r in desc(5, nB))}],')
        o.append(f'        desc_cells: &[{", ".join(arr(r) for r in desc(6, nA * nB))}], desc_all: {arr(col(7)[:4])},')
        o.append(f'        comp_a: {comp_src(comps(8, nA))}, comp_b: {comp_src(comps(18, nB))}, comp_cells: {comp_src(comps(28, nA * nB) if inter else [])},')
        o.append('    },')
o.append('];')
o.append('')

# ---------- nonparametric and correlation
all_cases = []
all_ds = []
for cpath, opath in [(np_cases, np_out)] + list(zip(extra[0::2], extra[1::2])):
    cs = json.load(open(cpath)); d = dumps(opath)
    assert len(cs) == len(d), (cpath, len(cs), len(d))
    all_cases += cs; all_ds += d

def clean(v):
    return [None if x is None else x for x in v]

o.append('pub struct Mw { pub name: &\'static str, pub x: &\'static [f64], pub y: &\'static [f64], pub tail: u8, pub exact: bool,')
o.append('    /// None where Origin shows no result (a group of one).')
o.append('    pub origin: Option<MwOrigin> }')
o.append('pub struct MwOrigin { pub rank_sum1: f64, pub rank_sum2: f64, pub u: f64, pub z: f64, pub p: f64, pub p2: f64 }')
o.append('pub struct Sr { pub name: &\'static str, pub x: &\'static [f64], pub y: &\'static [f64], pub median: f64, pub tail: u8,')
o.append('    pub t: f64, pub z: f64, pub p_exact: f64, pub p_asym: f64 }')
o.append('pub struct Kw { pub name: &\'static str, pub groups: &\'static [&\'static [f64]], pub n: &\'static [f64], pub mean_rank: &\'static [f64], pub rank_sum: &\'static [f64],')
o.append('    pub chi2: f64, pub df: f64, pub p: f64 }')
o.append('pub struct Cc { pub name: &\'static str, pub cols: &\'static [&\'static [f64]], pub listwise: bool,')
o.append('    /// Row-major k x k matrices of r and p for Pearson, Spearman and Kendall.')
o.append('    pub r: [&\'static [f64]; 3], pub p: [&\'static [f64]; 3] }')
o.append('')
tails = {'two': 0, 'upper': 1, 'lower': 2}
def datum(v): return f(float('nan') if v is None else v)
mw = []; sr = []; kw = []; cc = []
for c, rows in zip(all_cases, all_ds):
    k = c['kind']
    cols = c['cols']
    if k == 'mw':
        x, y = cols
        ex = c['exact']
        if cell(rows, 0, 14) is None:
            origin = 'None'
        else:
            p = cell(rows, 0, 16); p2 = cell(rows, 0, 17)
            origin = f'Some(MwOrigin {{ rank_sum1: {f(cell(rows,0,13))}, rank_sum2: {f(cell(rows,1,13))}, u: {f(cell(rows,0,14))}, z: {f(cell(rows,0,15))}, p: {f(p)}, p2: {f(p2)} }})'
        mw.append(f'    Mw {{ name: "{c["name"]}", x: &[{", ".join(datum(v) for v in x)}], y: &[{", ".join(datum(v) for v in y)}], tail: {tails[c["tail"]]}, exact: {"true" if ex else "false"}, origin: {origin} }},')
    elif k == 'sr1':
        x = cols[0]
        t = cell(rows, 0, 11); z = cell(rows, 0, 12); p1 = cell(rows, 0, 13); p2 = cell(rows, 0, 14)
        # layouts: [T, z, exact, asym]; [T, z, asym] (n > 80); [T, '', p] (nothing to rank)
        if p2 is None:
            pe, pa = (p1, None) if z is None else (None, p1)
        else:
            pe, pa = p1, p2
        sr.append(f'    Sr {{ name: "{c["name"]}", x: &[{", ".join(datum(v) for v in x)}], y: &[], median: {f(c["median"])}, tail: {tails[c["tail"]]}, t: {f(t)}, z: {f(z)}, p_exact: {f(pe)}, p_asym: {f(pa)} }},')
    elif k == 'sr2':
        x, y = cols
        t = cell(rows, 0, 14); z = cell(rows, 0, 15); p1 = cell(rows, 0, 16); p2 = cell(rows, 0, 17)
        if p2 is None:
            pe, pa = (p1, None) if z is None else (None, p1)
        else:
            pe, pa = p1, p2
        sr.append(f'    Sr {{ name: "{c["name"]}", x: &[{", ".join(datum(v) for v in x)}], y: &[{", ".join(datum(v) for v in y)}], median: 0.0, tail: {tails[c["tail"]]}, t: {f(t)}, z: {f(z)}, p_exact: {f(pe)}, p_asym: {f(pa)} }},')
    elif k == 'kw':
        n = len(cols)
        groups = '&[' + ', '.join('&[' + ', '.join(datum(v) for v in g) + ']' for g in cols) + ']'
        ns = [cell(rows, i, 12 - 7 + 0 + 0) for i in range(n)]  # placeholder, replaced below
        ns = [cell(rows, i, 11) for i in range(n)]
        mr = [cell(rows, i, 12) for i in range(n)]
        rs = [cell(rows, i, 13) for i in range(n)]
        kw.append(f'    Kw {{ name: "{c["name"]}", groups: {groups}, n: {sl(ns)}, mean_rank: {sl(mr)}, rank_sum: {sl(rs)}, chi2: {f(cell(rows,0,14))}, df: {f(cell(rows,0,15))}, p: {f(cell(rows,0,16))} }},')
    elif k == 'cc':
        n = len(cols)
        rr = []; pp = []
        for meth in range(3):
            off = 11 + n * meth
            R = []; P = []
            for i in range(n):
                for j in range(n):
                    R.append(cell(rows, 2 * i, off + j)); P.append(cell(rows, 2 * i + 1, off + j))
            rr.append(sl(R)); pp.append(sl(P))
        groups = '&[' + ', '.join('&[' + ', '.join(datum(v) for v in g) + ']' for g in cols) + ']'
        cc.append(f'    Cc {{ name: "{c["name"]}", cols: {groups}, listwise: {"true" if c.get("missing") == "listwise" else "false"}, r: [{", ".join(rr)}], p: [{", ".join(pp)}] }},')
o.append('pub const MW: &[Mw] = &[\n' + '\n'.join(mw) + '\n];')
o.append('pub const SR: &[Sr] = &[\n' + '\n'.join(sr) + '\n];')
o.append('pub const KW: &[Kw] = &[\n' + '\n'.join(kw) + '\n];')
o.append('pub const CC: &[Cc] = &[\n' + '\n'.join(cc) + '\n];')
open(out_path, 'w', encoding='utf-8').write('\n'.join(o) + '\n')
print('written', out_path, len(mw), len(sr), len(kw), len(cc))
