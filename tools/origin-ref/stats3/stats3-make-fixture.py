"""Turns the raw outputs of the Origin reference runs of the statistics-breadth tests (sign2, kstest2, mediantest,
friedman, grubbs, qtest, rowstats) into the Rust fixture file crates/calc/tests/fixtures/stats3_origin.rs.

The runs: gen.py, g2.py ... g5.py write the LabTalk scripts (lines format, run with
tools/origin-ref/run-labtalk-safe.ps1 and a trailing-backslash-free work folder); parse.py compact turns the raw
output into the stats3-p*.compact.txt files that are committed here; cases2..5.json hold the inputs.

usage: python -I stats3-make-fixture.py OUT.rs   (run inside this folder)
"""
import json, math, re, sys

NAN = 'f64::NAN'
SENTINEL = -1.23456789e-300  # Origin's "unassigned" value of an output variable


def f(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return NAN
    return repr(float(v))


def arr(vals):
    return '&[' + ', '.join(f(v) for v in vals) + ']'


def load_compact(path):
    sheets, vars_ = {}, {}
    cur = None
    for line in open(path, encoding='utf-8'):
        line = line.rstrip('\n')
        m = re.match(r'#SHEET (\S*)$', line)
        if m:
            cur = ('s', m.group(1)); sheets[m.group(1)] = {}; continue
        m = re.match(r'#VARS (\S+)$', line)
        if m:
            cur = ('v', m.group(1)); vars_[m.group(1)] = {}; continue
        if cur is None or not line:
            continue
        if cur[0] == 's':
            c, r, v = line.split(' ', 2)
            sheets[cur[1]][(int(c), int(r))] = v
        else:
            k, v = line.split('=', 1)
            vars_[cur[1]][k] = v
    return sheets, vars_


def num(s):
    if s is None or s == '--':
        return float('nan')
    return float(s)


cases = {}
for fn in ('cases2.json', 'cases3.json', 'cases4.json', 'cases5.json'):
    for c in json.load(open(fn)):
        cases[c['name']] = c
sheets, vars_ = {}, {}
for fn in ('stats3-p8.compact.txt', 'stats3-p9.compact.txt', 'stats3-p10.compact.txt', 'stats3-p11.compact.txt',
           'stats3-p12.compact.txt'):
    s, v = load_compact(fn)
    sheets.update(s); vars_.update(v)

TAILS = {'two': 0, 'upper': 1, 'lower': 2}
out = []
out.append('//! Numbers copied from Origin reference runs of sign2, kstest2, mediantest, friedman, grubbs, qtest and rowstats')
out.append('//! (generated by tools/origin-ref/stats3/stats3-make-fixture.py; scripts and compact raw output are in')
out.append('//! tools/origin-ref/stats3/). Do not edit by hand. A NaN is a number Origin does not show.')
out.append('#![allow(clippy::excessive_precision, dead_code)]')
out.append('')
out.append('pub struct SignCase { pub name: &\'static str, pub a: &\'static [f64], pub b: &\'static [f64], pub tail: u8,')
out.append('    /// Pairs with the first smaller, the second smaller, ties; the statistic, Z and p (NaN: not shown).')
out.append('    pub counts: [f64; 3], pub stat: f64, pub z: f64, pub p: f64 }')
out.append('pub struct KsCase { pub name: &\'static str, pub a: &\'static [f64], pub b: &\'static [f64], pub tail: u8,')
out.append('    pub n1: f64, pub n2: f64, pub d: f64, pub z: f64, pub p: f64 }')
out.append('pub struct MedianCase { pub name: &\'static str, pub groups: &\'static [&\'static [f64]], pub median: f64,')
out.append('    pub chi2: f64, pub df: f64, pub p: f64 }')
out.append('pub struct FriedmanCase { pub name: &\'static str, pub cols: &\'static [&\'static [f64]], pub mean_ranks: &\'static [f64],')
out.append('    pub rank_sums: &\'static [f64], pub chi2: f64, pub df: f64, pub p: f64 }')
out.append('pub struct OutlierCase { pub name: &\'static str, pub data: &\'static [f64], pub alpha: f64,')
out.append('    /// Suspect value, its row, statistic, critical value, approximate p (Grubbs only), significant.')
out.append('    pub value: f64, pub index: f64, pub stat: f64, pub critical: f64, pub p: f64, pub significant: f64 }')
out.append('pub struct RowStatsCase { pub name: &\'static str, pub cols: &\'static [&\'static [f64]],')
out.append('    /// Per row: mean, SD, SEM, minimum, maximum, N, sum.')
out.append('    pub rows: &\'static [[f64; 7]] }')
out.append('')

sign, ks, med, fr, gr, qt, row = [], [], [], [], [], [], []
for name, c in cases.items():
    cols = c['cols']
    if c['kind'] == 'sign':
        g = sheets.get(name)
        if g is None or g.get((3, 1)) != 'Signed Test':
            continue
        n1, n2, n3 = (num(g.get((12, r))) for r in (1, 2, 3))
        sign.append(f"    SignCase {{ name: {json.dumps(name)}, a: {arr(cols[0])}, b: {arr(cols[1])}, tail: {TAILS[c['tail']]}, "
                    f"counts: {arr([n1, n2, n3])[1:]}, stat: {f(num(g.get((13, 1))))}, z: {f(num(g.get((14, 1))))}, p: {f(num(g.get((15, 1))))} }},")
    elif c['kind'] == 'ks':
        g = sheets.get(name)
        if g is None or g.get((3, 1)) != 'Kolmogorov-Smirnov Test':
            continue
        ks.append(f"    KsCase {{ name: {json.dumps(name)}, a: {arr(cols[0])}, b: {arr(cols[1])}, tail: {TAILS[c['tail']]}, "
                  f"n1: {f(num(g.get((12, 1))))}, n2: {f(num(g.get((12, 2))))}, d: {f(num(g.get((13, 1))))}, z: {f(num(g.get((14, 1))))}, p: {f(num(g.get((15, 1))))} }},")
    elif c['kind'] == 'med':
        g = sheets.get(name)
        if g is None or g.get((3, 1)) != 'Median Test':
            continue
        groups = '&[' + ', '.join(arr(x) for x in cols) + ']'
        med.append(f"    MedianCase {{ name: {json.dumps(name)}, groups: {groups}, median: {f(num(g.get((12, 1))))}, "
                   f"chi2: {f(num(g.get((13, 1))))}, df: {f(num(g.get((14, 1))))}, p: {f(num(g.get((15, 1))))} }},")
    elif c['kind'] == 'fr':
        g = sheets.get(name)
        if g is None or g.get((3, 1)) != 'Friedman ANOVA':
            continue
        k = len(cols)
        mr = [num(g.get((13, r))) for r in range(1, k + 1)]
        rs = [num(g.get((14, r))) for r in range(1, k + 1)]
        groups = '&[' + ', '.join(arr(x) for x in cols) + ']'
        fr.append(f"    FriedmanCase {{ name: {json.dumps(name)}, cols: {groups}, mean_ranks: {arr(mr)}, rank_sums: {arr(rs)}, "
                  f"chi2: {f(num(g.get((15, 1))))}, df: {f(num(g.get((16, 1))))}, p: {f(num(g.get((17, 1))))} }},")
    elif c['kind'] in ('gr', 'qt'):
        v = vars_.get(name)
        if v is None:
            continue
        vals = {k: float(x) for k, x in v.items() if k != 'g$'}
        if all(x == 0 for x in vals.values()):
            continue  # Origin gave no result (too few numbers, or more than ten for Dixon)

        def un(x):
            return float('nan') if x == SENTINEL or x < -1e-300 and x > -1.3e-300 else x
        alpha = c.get('alpha', 0.05)
        sig = un(vals['f']) if c['kind'] == 'qt' else un(vals['f'])
        if vals['f'] == -1:
            continue  # constant data: no statistic (the run printed unassigned values)
        item = (f"    OutlierCase {{ name: {json.dumps(name)}, data: {arr(cols[0])}, alpha: {alpha}, value: {f(un(vals['a']))}, "
                f"index: {f(un(vals['b']))}, stat: {f(un(vals['c']))}, critical: {f(un(vals['d']))}, "
                f"p: {f(un(vals['e'])) if 'e' in vals else NAN}, significant: {f(sig)} }},")
        (gr if c['kind'] == 'gr' else qt).append(item)
    elif c['kind'] == 'row':
        g = sheets.get(name)
        if g is None:
            continue
        nc = len(cols)
        nrows = len(cols[0])
        rows = []
        for r in range(1, nrows + 1):
            rows.append([num(g.get((nc + 1 + j, r))) for j in range(7)])
        groups = '&[' + ', '.join(arr(x) for x in cols) + ']'
        row.append(f"    RowStatsCase {{ name: {json.dumps(name)}, cols: {groups}, rows: &[" + ', '.join('[' + ', '.join(f(x) for x in rr) + ']' for rr in rows) + '] },')

for title, ty, items in (('SIGN', 'SignCase', sign), ('KS', 'KsCase', ks), ('MEDIAN', 'MedianCase', med),
                         ('FRIEDMAN', 'FriedmanCase', fr), ('GRUBBS', 'OutlierCase', gr), ('DIXON', 'OutlierCase', qt),
                         ('ROWSTATS', 'RowStatsCase', row)):
    out.append(f'pub const {title}: &[{ty}] = &[')
    out.extend(items)
    out.append('];')
    out.append('')
open(sys.argv[1], 'w', encoding='utf-8').write('\n'.join(out))
print({t: len(i) for t, i in (('sign', sign), ('ks', ks), ('med', med), ('fr', fr), ('gr', gr), ('qt', qt), ('row', row))})
