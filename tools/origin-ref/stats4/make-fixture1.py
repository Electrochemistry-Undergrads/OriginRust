"""Turns holm1.out.txt (raw output of the Holm reference runs written by g1.py) into
crates/calc/tests/fixtures/stats4_origin.rs. usage: python make-fixture1.py OUT.rs   (inside this folder)"""
import json, math, sys
from parse1 import parse

def f(v):
    if v is None or v == '' or (isinstance(v, float) and math.isnan(v)):
        return 'f64::NAN'
    return repr(float(v))

cases = json.load(open('cases1.json')); res = parse('holm1.out.txt')
o = ['//! Numbers copied from Origin reference runs of the one-way ANOVA means comparisons with the Holm methods and the',
     '//! other statistics-breadth tools (generated by tools/origin-ref/stats4/make-fixture*.py; scripts and raw output',
     '//! are in tools/origin-ref/stats4/). Do not edit by hand. A NaN is a number Origin does not show.',
     '#![allow(clippy::excessive_precision, dead_code)]', '',
     'pub struct HolmRow { pub pair: usize, pub diff: f64, pub se: f64, pub stat: f64, pub p: f64, pub alpha: f64, pub sig: bool }',
     'pub struct HolmCase {',
     '    pub name: &\'static str, pub groups: &\'static [&\'static [f64]], pub alpha: f64,',
     '    /// 7 Bonferroni-Holm, 8 Sidak-Holm (Origin library numbering).',
     '    pub method: u8, pub rows: &\'static [HolmRow],',
     '}', '', 'pub const HOLM: &[HolmCase] = &[']
for ci, c in enumerate(cases):
    if c['name'] in ('const',):
        continue  # 0/0 in Origin; Sheaf says p = 1 (documented in statistics.md)
    k = len(c['groups']); npair = k * (k - 1) // 2
    for m in c['methods']:
        rc, rows = res[(ci, m)]
        assert rc == 0
        g = lambda r, j: rows[r][k + j] if k + j < len(rows[r]) else ''
        out = []
        for r in range(npair):
            out.append(f'HolmRow {{ pair: {int(float(g(r,1)))}, diff: {f(g(r,2))}, se: {f(g(r,3))}, stat: {f(g(r,5))}, '
                       f'p: {f(g(r,6))}, alpha: {f(g(r,7))}, sig: {"true" if float(g(r,8)) else "false"} }}')
        gs = ', '.join('&[' + ', '.join('f64::NAN' if v is None else repr(float(v)) for v in grp) + ']' for grp in c['groups'])
        o.append(f'    HolmCase {{ name: "{c["name"]}", groups: &[{gs}], alpha: {c["alpha"]}, method: {m}, rows: &[{", ".join(out)}] }},')
o.append('];')
open(sys.argv[1], 'w').write('\n'.join(o) + '\n')
