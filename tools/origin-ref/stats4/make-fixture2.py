"""Turns pss4.out.txt (raw output of the power / sample size runs written by g2.py) into
crates/calc/tests/fixtures/stats4_power_origin.rs. usage: python make-fixture2.py OUT.rs   (inside this folder)"""
import json, math, sys
from parse2 import parse

def f(v):
    if v is None or v == '' or (isinstance(v, float) and math.isnan(v)):
        return 'f64::NAN'
    return repr(float(v))

cases = json.load(open('cases2.json')); res = parse('pss4.out.txt')
o = ['//! Numbers copied from Origin reference runs of the power and sample size functions (generated by',
     '//! tools/origin-ref/stats4/make-fixture2.py; scripts and raw output are in tools/origin-ref/stats4/).',
     '//! Do not edit by hand. A NaN is a cell Origin leaves empty.',
     '#![allow(clippy::excessive_precision, dead_code)]', '',
     'pub struct PowerCase {',
     '    pub name: &\'static str,',
     '    /// 1 one-sample t, 2 two-sample t, 3 paired t, 4 one-way ANOVA.',
     '    pub kind: u8,',
     '    /// 0 powers of the given sample sizes, 1 sample sizes of the given powers.',
     '    pub mode: u8,',
     '    /// 0 two-sided, 1 one-sided.',
     '    pub tail: u8,',
     '    pub alpha: f64,',
     '    /// t tests: the two means (or the mean and the hypothesized value); ANOVA: the number of groups and the',
     '    /// corrected sum of squares of the group means.',
     '    pub a: f64,',
     '    pub b: f64,',
     '    pub sd: f64,',
     '    pub inputs: &\'static [f64],',
     '    /// Origin\'s return code: 0, -151 invalid input, -186 a wanted power below that of the smallest sample,',
     '    /// -187 no effect, -204 a wanted power outside (0, 1).',
     '    pub rc: i32,',
     '    pub outputs: &\'static [f64],',
     '    /// Power of the smallest sample (NaN: not given).',
     '    pub lowest: f64,',
     '}', '', 'pub const POWER: &[PowerCase] = &[']
for i, c in enumerate(cases):
    if c['name'] == 't2_big_effect_n':
        continue  # Origin's noncentral t breaks down for a noncentrality of 45 (lowest power 1, sample size 3, no error)
    rc, rows = res[i]
    n = len(c['vals'])
    outs = [rows[r][1] if r < len(rows) and len(rows[r]) > 1 else '' for r in range(n)]
    low = rows[0][2] if rows and len(rows[0]) > 2 else ''
    low = 'f64::NAN' if low in ('', '-1') else f(low)
    vals = ', '.join(repr(float(v)) for v in c['vals'])
    o.append(f'    PowerCase {{ name: "{c["name"]}", kind: {c["kind"]}, mode: {c["mode"]}, tail: {c["tail"]}, alpha: {c["alpha"]!r}, '
             f'a: {float(c["a"])!r}, b: {float(c["b"])!r}, sd: {float(c["sd"])!r}, inputs: &[{vals}], rc: {int(rc)}, '
             f'outputs: &[{", ".join(f(x) for x in outs)}], lowest: {low} }},')
o.append('];')
open(sys.argv[1], 'w').write('\n'.join(o) + '\n')
