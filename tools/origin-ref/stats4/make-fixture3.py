"""Turns the raw output of the 2D binning runs (g3.py, g4.py, g5.py) into
crates/calc/tests/fixtures/bin2d_origin.rs and a compact copy of what Origin returned (bin2d-origin.compact.json).
usage: python make-fixture3.py OUTDIR_WITH_binN.out.txt fixture.rs compact.json"""
import json, math, os, re, sys
from parse3 import parse

def opts_of(s):
    d = dict(re.findall(r'(\S+?):=(\S+)', s))
    def axis(a):
        g = lambda k: d.get(f'{a}.{k}')
        by_count = g('stepby') == '1' and g('intervals') is not None
        return dict(min=g('min'), max=g('max'), inc=None if by_count else g('inc'),
                    intervals=g('intervals') if by_count else None, centers=g('bin') == '0',
                    below=g('border.outleft') == '1', above=g('border.outright') == '1', periodic=g('periodical') == '1')
    return d.get('stats', 'count'), axis('x'), axis('y'), 'iz' in d

def f(v):
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return 'f64::NAN'
    r = repr(float(v))
    return r if ('.' in r or 'e' in r or 'inf' in r) else r + '.0'

def opt(v, kind=float):
    return 'None' if v is None else f'Some({f(float(v)) if kind is float else int(v)})'

def rs_axis(a):
    return (f"Axis {{ min: {opt(a['min'])}, max: {opt(a['max'])}, inc: {opt(a['inc'])}, "
            f"intervals: {opt(a['intervals'], int)}, centers: {str(a['centers']).lower()}, "
            f"below: {str(a['below']).lower()}, above: {str(a['above']).lower()} }}")

out_dir, fixture, compact = sys.argv[1], sys.argv[2], sys.argv[3]
rows_rs, kept = [], {}
for run in ('3', '4', '5'):
    path = os.path.join(out_dir, f'bin{run}.out.txt')
    if not os.path.exists(path):
        continue
    cases = {c['name']: c for c in json.load(open(f'cases{run}.json'))}
    for name, r in parse(path).items():
        c = cases[name]
        stat, ax, ay, iz = opts_of(c['opts'])
        if not r['ok'] or 'ncols' not in r or ax['periodic'] or ay['periodic'] or iz:
            continue
        ncols = int(r['ncols'])
        labels = []
        while (1, len(labels) + 1) in r['cells']:
            labels.append(r['cells'][(1, len(labels) + 1)])
        dumped = [k for k in range(2, ncols + 1) if (k, 1) in r['cells']]
        cells = [[(r['cells'][(k, i + 1)] if r['cells'][(k, i + 1)] != '--' else None) for k in dumped]
                 for i in range(len(labels))]
        comments = [r['comment'].get(k, '') for k in dumped]
        names = [r['lname'].get(k, '') for k in range(1, ncols + 1) if r['lname'].get(k) is not None]
        kept[name] = dict(opts=c['opts'], cols=c.get('cols', '(1,3)' if c['z'] is not None else '(1,2)'),
                          ncols=ncols, names=names, comments=comments, labels=labels, cells=cells)
        third = c['z'] is not None and c.get('cols', '(1,3)') == '(1,3)'
        x, y = c['x'], (c['z'] if third else c['y'])
        z = c['z'] if (c['z'] is not None and not third) else None
        rows_rs.append(
            f"    Bin2dCase {{\n        name: {json.dumps(name)},\n"
            f"        x: &[{', '.join(f(v) for v in x)}],\n        y: &[{', '.join(f(v) for v in y)}],\n"
            f"        z: {'None' if z is None else 'Some(&[' + ', '.join(f(v) for v in z) + '])'},\n"
            f"        stat: {json.dumps(stat)},\n        x_axis: {rs_axis(ax)},\n        y_axis: {rs_axis(ay)},\n"
            f"        first_name: {json.dumps(names[0])},\n        y_bins: {ncols - 1},\n"
            f"        row_labels: &[{', '.join(f(v) for v in labels)}],\n"
            f"        comments: &[{', '.join(json.dumps(s) for s in comments)}],\n"
            f"        cells: &[{', '.join('&[' + ', '.join(f(v) for v in row) + ']' for row in cells)}],\n    }},\n")
head = '''//! Numbers copied from Origin reference runs of the twoDBinning X-Function (2D Frequency Counts/Binning, worksheet
//! output), generated by tools/origin-ref/stats4/make-fixture3.py from the runs of g3.py, g4.py and g5.py (the
//! compact Origin output is tools/origin-ref/stats4/bin2d-origin.compact.json). Do not edit by hand. A NaN cell is
//! one Origin leaves empty ("--"); `cells` and `comments` cover the dumped columns, which can be fewer than `y_bins`.
#![allow(clippy::excessive_precision, clippy::approx_constant, dead_code)]

pub struct Axis {
    pub min: Option<f64>,
    pub max: Option<f64>,
    pub inc: Option<f64>,
    pub intervals: Option<usize>,
    pub centers: bool,
    pub below: bool,
    pub above: bool,
}

pub struct Bin2dCase {
    pub name: &'static str,
    pub x: &'static [f64],
    pub y: &'static [f64],
    /// The third column of an XYZ input (Origin ignores it).
    pub z: Option<&'static [f64]>,
    pub stat: &'static str,
    pub x_axis: Axis,
    pub y_axis: Axis,
    /// Long name of the first result column.
    pub first_name: &'static str,
    /// Number of Y bins (result columns after the first).
    pub y_bins: usize,
    /// The first column: one value per X bin.
    pub row_labels: &'static [f64],
    pub comments: &'static [&'static str],
    pub cells: &'static [&'static [f64]],
}

pub const BIN2D_CASES: &[Bin2dCase] = &[
'''
open(fixture, 'w', newline='\n').write(head + ''.join(rows_rs) + '];\n')
json.dump(kept, open(compact, 'w'), indent=0)
print(len(rows_rs), 'cases')
