"""Adds the cwt runs of c5.py, c6.py and c7.py (Origin 2016; outputs cwt5/6/7 .out and .cases) to t96-origin.json as
`cwt_more` (accepted runs: signal, scales, coefficient columns) and `cwt_refused` (runs Origin refused), then writes
crates/calc/tests/fixtures/cwt_origin.rs. Usage: python mkfix_cwt.py <folder with the .out files>  (the folder is
re-workspace/scratch/t96, local only); without an argument it only rewrites the Rust file from the JSON."""
import ast, json, os, sys

here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
from lib import parse, sig

jp = os.path.join(here, "t96-origin.json")
d = json.load(open(jp))
TYPES = ["Morlet", "DGauss", "MexHat"]


def imp(n, m):
    x = [0.0] * n
    x[m] = 1.0
    return x


if len(sys.argv) > 1:
    R = sys.argv[1]
    more, refused = [], []
    for fn, fixed in (("cwt5", {"S2": 0}), ("cwt6", {}), ("cwt7", {})):
        S = parse(open(os.path.join(R, fn + ".out")).read())
        for nm, ty, par, n, sc in ast.literal_eval(open(os.path.join(R, fn + ".cases")).read()):
            k = "[%s]CWTResults1" % nm
            if k not in S:
                refused.append(dict(name=nm, type=ty, param=par, scales=sc))
                continue
            if fn == "cwt5":
                x = imp(64, 32) if nm[0] == "F" else sig(n)
            else:
                x = {"S2": [1.0, 2.0], "S3": [1.0, 2.0, 0.5], "S1": [1.0]}.get(nm) or imp(64, 32)
            more.append(dict(name=nm, type=TYPES[ty], param=par, signal=x, scales=sc, cols=[[float(v) for v in c] for c in S[k]]))
    d["cwt_more"], d["cwt_refused"] = more, refused
    json.dump(d, open(jp, "w"), separators=(",", ":"))


def vec(v):
    return "&[" + ", ".join(repr(float(x)) for x in v) + "]"


cases = []
for c in d["cwt"]:
    x = [0.0] * c["n"]
    x[c["impulse_at"]] = c.get("impulse_value", 1.0)
    cases.append((c["name"], c["type"], c["param"], x, c["scales"], c["cols"]))
for c in d["cwt_more"]:
    cases.append((c["name"], c["type"], c["param"], c["signal"], c["scales"], c["cols"]))
out = ["// Generated by tools/origin-ref/t96/mkfix_cwt.py from t96-origin.json (Origin 2016 `cwt` runs, spec 19.6). Do not edit by hand.\n"]
out.append("/// `wavelet`: 0 Morlet, 1 DGauss, 2 MexHat; `cols`: one column per scale, as Origin wrote them.\n")
out.append("pub struct CwtCase { pub name: &'static str, pub wavelet: usize, pub param: f64, pub signal: &'static [f64], pub scales: &'static [f64], pub cols: &'static [&'static [f64]] }\n")
out.append("pub const CWT: &[CwtCase] = &[\n")
for nm, ty, par, x, sc, cols in cases:
    out.append('    CwtCase { name: "%s", wavelet: %d, param: %r, signal: %s, scales: %s, cols: &[%s] },\n' % (nm, TYPES.index(ty), float(par), vec(x), vec(sc), ", ".join(vec(c) for c in cols)))
out.append("];\n")
out.append("/// Runs Origin refused: `(wavelet, param, scales)`.\npub const CWT_REFUSED: &[(usize, f64, &[f64])] = &[\n")
for r in d["cwt_refused"]:
    out.append("    (%d, %r, %s),\n" % (r["type"], float(r["param"]), vec(r["scales"])))
out.append("];\n")
open(os.path.join(here, "..", "..", "..", "crates", "calc", "tests", "fixtures", "cwt_origin.rs"), "w").write("".join(out))
