"""Writes crates/calc/tests/fixtures/wavelet_origin.rs from t96-origin.json (Origin 2016 numbers, discrete tools only)."""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, "t96-origin.json")))
out = ["// Generated by tools/origin-ref/t96/mkfix_rs.py from t96-origin.json (Origin 2016 runs, spec 19). Do not edit by hand.\n"]


def vec(v):
    return "&[" + ", ".join(repr(float(x)) for x in v) + "]"


def q(s):
    return '"' + s + '"'


def opt(v):
    return "None" if v is None else "Some(" + vec(v) + ")"


out.append("pub const DWT_INPUT16: &[f64] = %s;\n" % vec(d["dwt_input16"]))
out.append("pub const DWT_INPUT21: &[f64] = %s;\n" % vec(d["dwt_input21"]))
out.append("pub const NOISY128: &[f64] = %s;\n" % vec(d["denoise_input128"]))
assert d["denoise_input128"] == d["smooth_input128"]
out.append("/// `(type, ext, n, ca, cd)` of `dwt`.\npub struct DwtCase { pub wavelet: usize, pub ext: usize, pub n: usize, pub ca: &'static [f64], pub cd: &'static [f64] }\n")
out.append("pub const DWT: &[DwtCase] = &[\n")
for e in d["dwt"]:
    out.append("    DwtCase { wavelet: %d, ext: %d, n: %d, ca: %s, cd: %s },\n" % (e["type"], e["ext"], e["n"], vec(e["ca"]), vec(e["cd"])))
out.append("];\n")
out.append("pub struct IdwtCase { pub name: &'static str, pub wavelet: usize, pub ext: usize, pub ca: &'static [f64], pub cd: &'static [f64], pub out: &'static [f64] }\n")
out.append("pub const IDWT: &[IdwtCase] = &[\n")
for e in d["idwt"]:
    out.append("    IdwtCase { name: %s, wavelet: %d, ext: %d, ca: %s, cd: %s, out: %s },\n" % (q(e["name"]), e["type"], e["ext"], vec(e["ca"]), vec(e["cd"]), vec(e["out"])))
out.append("];\n")
out.append("pub struct DenoiseCase { pub wavelet: &'static str, pub ext: &'static str, pub thrt: &'static str, pub level: usize, pub thrd: f64, pub out: Option<&'static [f64]> }\n")
out.append("pub const DENOISE: &[DenoiseCase] = &[\n")
for e in d["denoise"]:
    out.append("    DenoiseCase { wavelet: %s, ext: %s, thrt: %s, level: %d, thrd: %r, out: %s },\n" % (q(e["type"]), q(e["ext"]), q(e["thrt"]), e["level"], float(e["thrd"]), opt(e["out"])))
out.append("];\n")
out.append("pub struct BoundaryCase { pub name: &'static str, pub input: &'static [f64], pub out: &'static [f64] }\n")
out.append("/// db2, periodic, custom, level 1, thrd 50.\npub const BOUNDARY: &[BoundaryCase] = &[\n")
for e in d["denoise_boundary"]:
    assert (e["type"], e["ext"], e["thrt"], e["level"], e["thrd"]) == ("db2", "periodic", "custom", 1, 50)
    out.append("    BoundaryCase { name: %s, input: %s, out: %s },\n" % (q(e["name"]), vec(e["input"]), vec(e["out"])))
out.append("];\n")
out.append("pub struct SmoothCase { pub wavelet: &'static str, pub ext: &'static str, pub cutoff: f64, pub n: usize, pub out: &'static [f64] }\n")
out.append("pub const SMOOTH: &[SmoothCase] = &[\n")
for e in d["smooth"]:
    out.append("    SmoothCase { wavelet: %s, ext: %s, cutoff: %r, n: %d, out: %s },\n" % (q(e["type"]), q(e["ext"]), float(e["cutoff"]), e["n"], vec(e["out"])))
out.append("];\n")
out.append("/// `(n, dropped below, kept above)` of the sqtwolog threshold, db2 periodic level 1.\npub const SQTWOLOG: &[(usize, f64, f64)] = &[\n")
for r in d["sqtwolog_threshold_brackets"]["rows"]:
    out.append("    (%d, %r, %r),\n" % (r["n"], r["lo"], r["hi"]))
out.append("];\n")
open(os.path.join(here, "..", "..", "..", "crates", "calc", "tests", "fixtures", "wavelet_origin.rs"), "w").write("".join(out))
